import os
import json
import logging
from ml.pipeline import run_pipeline
from backend.app.services.video_service import extract_audio

log = logging.getLogger("pipeline_service")
OUTPUTS_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../data/outputs"))

def update_status(job_id: str, status: str, step: str = "", results: dict = None, error: str = None):
    os.makedirs(OUTPUTS_DIR, exist_ok=True)
    status_file = os.path.join(OUTPUTS_DIR, f"{job_id}.json")
    
    data = {
        "job_id": job_id,
        "status": status,
        "step": step,
    }
    if results:
        data["results"] = results
    if error:
        data["error"] = error
        
    with open(status_file, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

def generate_markdown_minutes(results: dict) -> str:
    md = []
    meta = results.get("metadata", {})
    title = meta.get("title", "Meeting Minutes")
    if not title or title == "Not specified":
        title = "Meeting Minutes"
    date = meta.get("date", "Not specified")
    participants = meta.get("participants", [])

    md.append(f"# {title}\n")
    if date != "Not specified" or participants:
        md.append("### Overview")
        if date != "Not specified":
            md.append(f"- **Date:** {date}")
        if participants:
            md.append(f"- **Participants:** {', '.join(participants)}")
        md.append("")

    summary = results.get("summary", "")
    if summary:
        md.append("## Executive Summary")
        md.append(summary + "\n")

    key_points = results.get("key_points", [])
    if key_points:
        md.append("## Key Discussion Points")
        for kp in key_points:
            md.append(f"- {kp}")
        md.append("")

    decisions = results.get("decisions", [])
    if decisions:
        md.append("## Decisions Agreed Upon")
        for d in decisions:
            md.append(f"- {d.get('text', '')}")
        md.append("")
    else:
        md.append("## Decisions Agreed Upon")
        md.append("_No confirmed decisions were detected in this recording._\n")

    actions = results.get("action_items", [])
    if actions:
        md.append("## Action Items & Next Steps")
        md.append("| Action | Owner | Deadline |")
        md.append("| :--- | :--- | :--- |")
        for a in actions:
            text = a.get("text", "").replace("|", "-")
            owner = a.get("owner") or "Not identified"
            deadline = a.get("deadline") or "Not specified"
            md.append(f"| {text} | {owner} | {deadline} |")
        md.append("")
    else:
        md.append("## Action Items & Next Steps")
        md.append("_No confirmed action items were detected in this recording._\n")

    follow_ups = results.get("follow_ups", [])
    if follow_ups:
        md.append("## Follow-Ups")
        for f in follow_ups:
            md.append(f"- {f.get('text', '')}")
        md.append("")

    # Append pipeline metadata note
    info = results.get("pipeline_info", {})
    if info:
        md.append("---")
        md.append("*Generated by the Automated Meeting Minutes Generator (Team 14).*")
        md.append(f"*Transcription: {info.get('transcription_model', 'Whisper')} · "
                  f"Summarization: {info.get('summarization_model', 'DistilBART')}*")

    return "\n".join(md)


def process_meeting_background(job_id: str, file_path: str, is_video: bool):
    """
    Background task to run the complete pipeline.
    """
    try:
        update_status(job_id, "processing", "starting")
        
        audio_path = file_path
        if is_video:
            update_status(job_id, "processing", "extracting_audio")
            audio_path = extract_audio(file_path, OUTPUTS_DIR)
            
        def status_callback(step: str):
            update_status(job_id, "processing", step)

        results = run_pipeline(
            input_path=audio_path,
            meeting_id=job_id,
            status_callback=status_callback
        )
        
        if "error" in results:
            update_status(job_id, "failed", error=results["error"])
        else:
            update_status(job_id, "completed", results=results)
            
            # Save raw txt and complete formatted md for downloads
            with open(os.path.join(OUTPUTS_DIR, f"{job_id}.txt"), "w", encoding="utf-8") as f:
                f.write(results.get("transcript", ""))
                
            with open(os.path.join(OUTPUTS_DIR, f"{job_id}.md"), "w", encoding="utf-8") as f:
                f.write(generate_markdown_minutes(results))
                
    except Exception as e:
        log.exception("Pipeline failed")
        update_status(job_id, "failed", error=str(e))
    finally:
        # Cleanup uploaded file if it's in temp uploads
        if os.path.exists(file_path) and "uploads" in file_path:
            try:
                os.remove(file_path)
            except:
                pass
        # Cleanup extracted audio
        if is_video and audio_path and os.path.exists(audio_path):
            try:
                os.remove(audio_path)
            except:
                pass
